-- True Concept — initial schema.
-- Replaces the SQLite tables previously created at runtime by database.js.
-- Apply with: supabase db push, or paste into the SQL editor / MCP execute_sql.

create table if not exists users (
    id         bigint generated by default as identity primary key,
    name       text not null,
    email      text unique not null,
    password   text not null,
    role       text not null default 'customer',
    created_at timestamptz not null default now()
);

create table if not exists services (
    id          bigint generated by default as identity primary key,
    name        text not null,
    description text not null,
    price       numeric(12, 2) not null,
    image       text,
    created_at  timestamptz not null default now()
);

create table if not exists requests (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null references users (id) on delete cascade,
    service_id bigint not null references services (id) on delete cascade,
    details    text not null,
    status     text not null default 'pending',
    created_at timestamptz not null default now()
);

create index if not exists requests_user_id_idx on requests (user_id);
create index if not exists requests_status_idx on requests (status);

-- The app reaches these tables only through the server's Postgres connection,
-- which bypasses RLS. Enabling RLS with no policies keeps the public REST API
-- (anon / publishable keys) from reading users or requests.
alter table users enable row level security;
alter table services enable row level security;
alter table requests enable row level security;
