/**
 * Builds the static preview at the repo root (used by GitHub Pages).
 *
 * GitHub Pages serves a single index.html, so the stylesheet, script and the
 * work screenshots are all inlined.
 * Regenerate after editing views/index.ejs, public/css/home.css,
 * public/js/home.js or public/images/work/*:
 *
 *     npm run build:static
 */
const fs = require('fs');
const path = require('path');
const ejs = require('ejs');

const root = path.join(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');

// The preview is a mirror of the real site, so it advertises the real URLs.
const SITE_URL = 'https://company-website-n9ba.vercel.app';

const template = read('views/index.ejs');
const css = read('public/css/home.css');
const js = read('public/js/home.js');

// filename lets include() resolve partials the way the Express views do.
let html = ejs.render(template, { staticPreview: true, siteUrl: SITE_URL }, {
    filename: path.join(root, 'views', 'index.ejs')
});

// Server routes do not exist on a static host — point them at the section.
html = html.split('href="/services"').join('href="#services"');
// A static host has no /images or manifest here, so the icon is inlined and the
// manifest link dropped rather than served as a 404.
const icon = fs.readFileSync(path.join(root, 'public/images/4.png')).toString('base64');
html = html.replace(/href="\/images\/4\.png"/g, 'href="data:image/png;base64,' + icon + '"');
html = html.replace(/\n\s*<link rel="manifest" href="\/site\.webmanifest">/, '');

const styleTag = '<link rel="stylesheet" href="/css/home.css">';
const scriptTag = '<script src="/js/home.js"></script>';

if (!html.includes(styleTag) || !html.includes(scriptTag)) {
    throw new Error('Expected stylesheet/script tags in views/index.ejs — update build-static.js');
}

html = html.replace(styleTag, '<style>\n' + css + '\n</style>');
// The preview has no API, so the brief falls back to the visitor's email app.
html = html.replace(scriptTag, '<script>window.TC_STATIC = true;</script>\n<script>\n' + js + '\n</script>');

// Inline work screenshots: the preview is a single file, so nothing can 404.
html = html.replace(/src="(\/images\/work\/[^"]+)"/g, (match, src) => {
    const file = path.join(root, 'public', src.replace(/^\//, ''));
    if (!fs.existsSync(file)) {
        throw new Error('Missing image referenced by views/index.ejs: ' + src);
    }
    const mime = /\.jpe?g$/i.test(file) ? 'image/jpeg' : 'image/png';
    const base64 = fs.readFileSync(file).toString('base64');
    return 'src="data:' + mime + ';base64,' + base64 + '"';
});

html = html.replace(
    '<!DOCTYPE html>',
    '<!DOCTYPE html>\n<!-- Generated by scripts/build-static.js — edit views/index.ejs instead. -->'
);

fs.writeFileSync(path.join(root, 'index.html'), html);
console.log('index.html written (' + Math.round(html.length / 1024) + ' KB)');
